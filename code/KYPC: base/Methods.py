# .strip() — убирает пробелы/символы с краёв (lstrip/rstrip — только слева/справа)
# .replace(old, new) — заменяет подстроку
# .lower() / .upper() / .title() / .capitalize() — изменение регистра
# .find() / .index() — ищет подстроку, возвращает позицию (find возвращает -1 если нет, index кидает ошибку)
# .format() или f-strings (но это не метод, а синтаксис)** — форматирование
# .split() - строку в список, .join() - наоборот
